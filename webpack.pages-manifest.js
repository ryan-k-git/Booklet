const fs = require("fs");
const path = require("path");
const { Compilation, sources } = require("webpack");

const PAGES_DIR = path.resolve(__dirname, "pages");
const SOURCE_MANIFEST_PATH = path.resolve(__dirname, "js/pages.js");
const OUTPUT_MANIFEST_PATH = "js/pages.js";
const IMAGE_EXTENSION = /\.(avif|gif|jpe?g|png|svg|webp)$/i;

const listPages = () => {
  let entries;

  try {
    entries = fs.readdirSync(PAGES_DIR, { withFileTypes: true });
  } catch {
    return [];
  }

  return entries
    .filter((entry) => entry.isFile() && IMAGE_EXTENSION.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }))
    .map((name) => `pages/${name}`);
};

const manifestSource = () => {
  const pages = JSON.stringify(listPages(), null, 2);

  return `// Generated by webpack.pages-manifest.js. Do not edit by hand.\nwindow.BOOKLET_PAGES = ${pages};\n`;
};

/*
 * Writes js/pages.js in the source tree so the booklet also works when the
 * source folder is served directly, and emits the same file into the build.
 */
const writeSourceManifest = () => {
  const next = manifestSource();
  let current = "";

  try {
    current = fs.readFileSync(SOURCE_MANIFEST_PATH, "utf8");
  } catch {
    // The generated file does not exist yet.
  }

  if (next !== current) {
    fs.writeFileSync(SOURCE_MANIFEST_PATH, next);
  }
};

class PagesManifestPlugin {
  apply(compiler) {
    writeSourceManifest();

    compiler.hooks.watchRun.tap("PagesManifestPlugin", writeSourceManifest);

    compiler.hooks.thisCompilation.tap("PagesManifestPlugin", (compilation) => {
      compilation.hooks.processAssets.tap(
        {
          name: "PagesManifestPlugin",
          stage: Compilation.PROCESS_ASSETS_STAGE_ADDITIONAL,
        },
        () => {
          compilation.emitAsset(OUTPUT_MANIFEST_PATH, new sources.RawSource(manifestSource()));
        }
      );
    });

    compiler.hooks.afterCompile.tap("PagesManifestPlugin", (compilation) => {
      compilation.contextDependencies.add(PAGES_DIR);
    });
  }
}

module.exports = PagesManifestPlugin;
